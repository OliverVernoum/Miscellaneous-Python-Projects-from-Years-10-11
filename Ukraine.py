import turtle

turtle.fillcolor ("Yellow")
turtle.begin_fill()
turtle.forward (1000)
turtle.left(90)
turtle.forward(500)
turtle.left(90)
turtle.forward (2000)
turtle.left (90)
turtle.forward(500)
turtle.end_fill()
turtle.goto(0,0)
turtle.fillcolor ("Blue")
turtle.begin_fill()
turtle.left(90)
turtle.forward (1000)
turtle.right(90)
turtle.forward(500)
turtle.right(90)
turtle.forward (2000)
turtle.right (90)
turtle.forward(500)
turtle.end_fill()
turtle.done()

